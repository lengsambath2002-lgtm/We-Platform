package com.businessplatform.ops.repository;

import java.time.LocalDate;
import java.util.List;
import java.util.Optional;
import java.util.UUID;

import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.Lock;
import org.springframework.data.jpa.repository.Query;

import com.businessplatform.ops.domain.MaintenancePlan;

import jakarta.persistence.LockModeType;

public interface MaintenancePlanRepository extends JpaRepository<MaintenancePlan, UUID> {

    Optional<MaintenancePlan> findByIdAndOrgId(UUID id, UUID orgId);

    List<MaintenancePlan> findByOrgIdOrderByNextDue(UUID orgId);

    List<MaintenancePlan> findByOrgIdAndAssetIdOrderByNextDue(UUID orgId, UUID assetId);

    /** The plan, locked until the transaction ends (two generators never both make its next work order). */
    @Lock(LockModeType.PESSIMISTIC_WRITE)
    @Query("SELECT p FROM MaintenancePlan p WHERE p.id = :id")
    Optional<MaintenancePlan> lock(UUID id);

    /** Ids of the organisation's active plans whose next work order is due to be generated by {@code today}. */
    @Query(value = "SELECT id FROM svc_maintenance_plan WHERE org_id = :orgId AND active"
            + " AND next_due - lead_days <= :today ORDER BY next_due", nativeQuery = true)
    List<UUID> dueIds(UUID orgId, LocalDate today);

    /** Organisations with Service &amp; Operations on and at least one plan due to be generated. */
    @Query(value = "SELECT DISTINCT p.org_id FROM svc_maintenance_plan p JOIN org_module m ON m.org_id = p.org_id"
            + " AND m.module_key = 'service' AND m.enabled WHERE p.active AND p.next_due - p.lead_days <= :today",
            nativeQuery = true)
    List<UUID> orgsWithDue(LocalDate today);

    /** Active plans due in {@code from}–{@code to}. */
    @Query("SELECT p FROM MaintenancePlan p WHERE p.orgId = :orgId AND p.active AND p.nextDue BETWEEN :from AND :to"
            + " ORDER BY p.nextDue")
    List<MaintenancePlan> dueBetween(UUID orgId, LocalDate from, LocalDate to);
}
