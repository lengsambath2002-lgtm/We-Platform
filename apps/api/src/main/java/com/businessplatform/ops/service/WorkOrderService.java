/**
 * Work orders (WO-0001): created by dispatchers and Admins from a ticket or on their own (or generated by a
 * maintenance plan), with technicians, a scheduled window, a checklist and parts / labour lines whose totals only
 * the server computes. DRAFT ─schedule─► SCHEDULED: when the total is above the organisation's threshold the
 * schedule goes through the approval engine first (default workflow "Work order approval": an Admin) and the work
 * order is scheduled when it is approved. Technicians see only their own work orders: they start, hold, tick the
 * checklist, record parts and labour, and complete with notes and the customer's sign-off name.
 */
