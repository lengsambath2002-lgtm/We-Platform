    @Transactional
    public WorkOrderView start(String slug, UUID id) {
        OpsAccess.Who w = access.require(slug);
        WorkOrder o = lock(w, id);
        if (!WorkOrder.SCHEDULED.equals(o.getStatus()) && !WorkOrder.ON_HOLD.equals(o.getStatus())) {
            throw new BusinessException(ErrorCode.INVALID_STATE, "Only a scheduled or on-hold work order can be started", List.of());
        }
        String from = o.getStatus();
        o.setStatus(WorkOrder.IN_PROGRESS);
        o.setHoldReason(null);
        if (o.getStartedAt() == null) {
            o.setStartedAt(clock.instant());
        }
        o.setUpdatedAt(clock.instant());
        activity.record(w.orgId(), OpsAccess.MODULE, RECORD, o.getId(), w.userId(),
                WorkOrder.ON_HOLD.equals(from) ? "service.workorder.resumed" : "service.workorder.started", Map.of("number", o.getNumber()));
        return view(w, o);
    }

    @Transactional
    public WorkOrderView hold(String slug, UUID id, String reason) {
        OpsAccess.Who w = access.require(slug);
        WorkOrder o = lock(w, id);
        if (!WorkOrder.IN_PROGRESS.equals(o.getStatus())) {
            throw new BusinessException(ErrorCode.INVALID_STATE, "Only a work order in progress can be put on hold", List.of());
        }
        o.setStatus(WorkOrder.ON_HOLD);
        o.setHoldReason(reason.strip());
        o.setUpdatedAt(clock.instant());
        activity.record(w.orgId(), OpsAccess.MODULE, RECORD, o.getId(), w.userId(), "service.workorder.held",
                Map.of("number", o.getNumber(), "reason", o.getHoldReason()));
        return view(w, o);
    }

    /** Completes the work: every checklist item ticked, notes and the name of the customer who signs it off. */
    @Transactional
    public WorkOrderView complete(String slug, UUID id, CompleteRequest in) {
        OpsAccess.Who w = access.require(slug);
        WorkOrder o = lock(w, id);
        if (!WorkOrder.IN_PROGRESS.equals(o.getStatus())) {
            throw new BusinessException(ErrorCode.INVALID_STATE, "Start the work order before completing it", List.of());
        }
        if (checklist.findByWorkOrderIdOrderByPosition(o.getId()).stream().anyMatch(c -> !c.isDone())) {
            throw BusinessException.field(ErrorCode.VALIDATION_FAILED, "checklist", "Tick every checklist item first");
        }
        Instant now = clock.instant();
        o.setStatus(WorkOrder.COMPLETED);
        o.setCompletedAt(now);
        o.setCompletedBy(w.userId());
        o.setCompletionNotes(OpsPeople.clean(in.notes()));
        o.setSignedBy(in.signedBy().strip());
        o.setUpdatedAt(now);
        activity.record(w.orgId(), OpsAccess.MODULE, RECORD, o.getId(), w.userId(), "service.workorder.completed",
                Map.of("number", o.getNumber(), "signedBy", o.getSignedBy(), "total", o.getTotal().toPlainString()));
        if (o.getCreatedBy() != null) {
            notifications.send(w.orgId(), List.of(o.getCreatedBy()), w.userId(), "service.workorder.completed",
                    Text.of("Work order completed: {number}", Map.of("number", o.getNumber())), Text.raw(o.getTitle()),
                    link(w.ctx().slug(), o.getId()));
        }
        return view(w, o);
    }

    @Transactional
    public WorkOrderView check(String slug, UUID id, UUID itemId, boolean done) {
        OpsAccess.Who w = access.require(slug);
        WorkOrder o = lock(w, id);
        if (!WORKING.contains(o.getStatus())) {
            throw new BusinessException(ErrorCode.INVALID_STATE, "The checklist can be ticked once the work order is scheduled", List.of());
        }
        ChecklistItem c = checklist.findByIdAndWorkOrderId(itemId, o.getId()).orElseThrow(BusinessException::notFound);
        if (c.isDone() != done) {
            c.setDone(done);
            c.setDoneBy(done ? w.userId() : null);
            c.setDoneAt(done ? clock.instant() : null);
            activity.record(w.orgId(), OpsAccess.MODULE, RECORD, o.getId(), w.userId(),
                    done ? "service.workorder.checked" : "service.workorder.unchecked", Map.of("number", o.getNumber(), "label", c.getLabel()));
        }
        return view(w, o);
    }

    /**
     * Replaces the parts and labour lines. Dispatchers and Admins until it is completed (not while it waits for
     * approval); its technicians while they work on it (in progress or on hold).
     */
    @Transactional
    public WorkOrderView setLines(String slug, UUID id, List<LineInput> in) {
        OpsAccess.Who w = access.require(slug);
        WorkOrder o = lock(w, id);
        if (!canEditLines(w, o)) {
            if (o.isOpen() && !w.manager()) {
                throw new BusinessException(ErrorCode.INVALID_STATE, "Start the work order to record parts and labour", List.of());
            }
            throw new BusinessException(ErrorCode.INVALID_STATE, "The parts and labour can't be changed any more", List.of());
        }
        requireNotWaiting(w, o);
        setLines(o, in);
        afterTotalsChanged(o);
        activity.record(w.orgId(), OpsAccess.MODULE, RECORD, o.getId(), w.userId(), "service.workorder.lines",
                Map.of("number", o.getNumber(), "total", o.getTotal().toPlainString()));
        return view(w, o);
    }

    /** The approval engine closed a work order's approval: scheduled when approved (if still a ready draft). */
    @EventListener
    @Transactional
    public void onApprovalClosed(ApprovalClosed ev) {
        if (!OpsAccess.MODULE.equals(ev.module()) || !RECORD.equals(ev.recordType())) {
            return;
        }
        workOrders.lock(ev.recordId(), ev.ctx().orgId())
                .filter(o -> WorkOrder.PENDING.equals(o.getApprovalState()) && ev.requestId().equals(o.getApprovalId()))
                .ifPresent(o -> {
                    switch (ev.status()) {
                        case "APPROVED" -> {
                            approved(o);
                            if (WorkOrder.DRAFT.equals(o.getStatus()) && o.getScheduledStart() != null
                                    && !views.technicians(o.getId()).isEmpty()) {
                                toScheduled(o, ev.ctx().slug(), ev.ctx().userId());
                            }
                        }
                        case "REJECTED" -> o.setApprovalState(WorkOrder.REJECTED);
                        default -> o.setApprovalState(WorkOrder.NONE);
                    }
                    o.setUpdatedAt(clock.instant());
                });
    }

