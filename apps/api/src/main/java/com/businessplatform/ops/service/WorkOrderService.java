    /** A new work order of a maintenance plan (the caller holds the plan's lock and checked it isn't there yet). */
    @Transactional
    WorkOrder generated(UUID orgId, String slug, UUID actorId, com.businessplatform.ops.domain.MaintenancePlan p, Asset a) {
        WorkOrder o = blank(orgId, actorId);
        o.setNumber(settings.nextNumber(orgId, "WORK_ORDER"));
        o.setTitle(p.getTitle());
        o.setPriority("MEDIUM");
        o.setCustomerId(a.getCustomerId());
        o.setSiteId(a.getSiteId());
        o.setAssetId(a.getId());
        o.setPlanId(p.getId());
        o.setPlanDue(p.getNextDue());
        // The due day, 09:00–12:00 local time.
        o.setScheduledStart(p.getNextDue().atTime(9, 0).atZone(CalendarService.ZONE).toInstant());
        o.setScheduledEnd(p.getNextDue().atTime(12, 0).atZone(CalendarService.ZONE).toInstant());
        o = workOrders.saveAndFlush(o);
        boolean tech = p.getTechnicianId() != null && access.technician(orgId, p.getTechnicianId());
        if (tech) {
            technicians.save(new WoTechnician(o.getId(), p.getTechnicianId(), orgId));
        }
        setChecklist(o, p.getChecklist());
        activity.record(orgId, OpsAccess.MODULE, RECORD, o.getId(), actorId, "service.workorder.generated",
                Map.of("number", o.getNumber(), "title", o.getTitle(), "due", p.getNextDue().toString()));
        if (tech) {
            toScheduled(o, slug, actorId);
        }
        return o;
    }

    WorkOrder visible(OpsAccess.Who w, UUID id) {
        WorkOrder o = workOrders.findByIdAndOrgId(id, w.orgId()).orElseThrow(BusinessException::notFound);
        if (!w.manager() && !technicians.existsByWorkOrderIdAndUserId(o.getId(), w.userId())) {
            throw BusinessException.notFound();
        }
        return o;
    }

    public static String link(String slug, UUID id) {
        return "/" + slug + "/service/work-orders/" + id;
    }

