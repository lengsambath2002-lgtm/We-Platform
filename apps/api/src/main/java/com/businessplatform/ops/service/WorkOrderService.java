    private WorkOrder lock(OpsAccess.Who w, UUID id) {
        WorkOrder o = workOrders.lock(id, w.orgId()).orElseThrow(BusinessException::notFound);
        if (!w.manager() && !technicians.existsByWorkOrderIdAndUserId(o.getId(), w.userId())) {
            throw BusinessException.notFound();
        }
        return o;
    }

    private WorkOrder blank(UUID orgId, UUID by) {
        WorkOrder o = new WorkOrder();
        o.setId(Ids.next());
        o.setOrgId(orgId);
        o.setStatus(WorkOrder.DRAFT);
        o.setApprovalState(WorkOrder.NONE);
        o.setPartsTotal(WoLine.ZERO);
        o.setLabourTotal(WoLine.ZERO);
        o.setTotal(WoLine.ZERO);
        o.setCreatedBy(by);
        o.setCreatedAt(clock.instant());
        o.setUpdatedAt(clock.instant());
        return o;
    }

    private void details(OpsAccess.Who w, WorkOrder o, WorkOrderRequest in, UUID customerId, UUID siteId, UUID assetId,
            boolean sameCustomer) {
        customers.checkLink(w.orgId(), customerId, siteId, sameCustomer);
        Asset a = assets.checkLink(w.orgId(), assetId, customerId);
        if (a != null && customerId == null) {
            customerId = a.getCustomerId();
        }
        if ((in.scheduledStart() == null) != (in.scheduledEnd() == null)) {
            throw BusinessException.field(ErrorCode.VALIDATION_FAILED, "scheduledEnd", "Give both the start and the end");
        }
        if (in.scheduledStart() != null && !in.scheduledEnd().isAfter(in.scheduledStart())) {
            throw BusinessException.field(ErrorCode.VALIDATION_FAILED, "scheduledEnd", "The end is before the start");
        }
        if (!WorkOrder.DRAFT.equals(o.getStatus()) && in.scheduledStart() == null) {
            throw BusinessException.field(ErrorCode.VALIDATION_FAILED, "scheduledStart", "A scheduled work order keeps its window");
        }
        o.setTitle(in.title().strip());
        o.setDescription(OpsPeople.clean(in.description()));
        o.setPriority(in.priority());
        o.setCustomerId(customerId);
        o.setSiteId(siteId);
        o.setAssetId(assetId);
        o.setScheduledStart(in.scheduledStart());
        o.setScheduledEnd(in.scheduledEnd());
        o.setUpdatedAt(clock.instant());
    }

    private void setTechnicians(OpsAccess.Who w, WorkOrder o, List<UUID> ids) {
        List<UUID> wanted = new ArrayList<>(new LinkedHashSet<>(ids));
        for (UUID u : wanted) {
            if (!access.technician(w.orgId(), u)) {
                throw BusinessException.field(ErrorCode.VALIDATION_FAILED, "technicianIds", "Choose active technicians");
            }
        }
        technicians.deleteByWorkOrderId(o.getId());
        technicians.flush();
        wanted.forEach(u -> technicians.save(new WoTechnician(o.getId(), u, w.orgId())));
    }

    /** Replaces the checklist; items kept by label keep their ticks. */
    private void setChecklist(WorkOrder o, List<String> labels) {
        Map<String, ChecklistItem> old = new HashMap<>();
        checklist.findByWorkOrderIdOrderByPosition(o.getId()).forEach(c -> old.putIfAbsent(c.getLabel(), c));
        checklist.deleteByWorkOrderId(o.getId());
        checklist.flush();
        short pos = 1;
        for (String label : labels) {
            String l = label.strip();
            ChecklistItem was = old.get(l);
            ChecklistItem c = new ChecklistItem();
            c.setId(Ids.next());
            c.setOrgId(o.getOrgId());
            c.setWorkOrderId(o.getId());
            c.setPosition(pos++);
            c.setLabel(l);
            if (was != null && was.isDone()) {
                c.setDone(true);
                c.setDoneBy(was.getDoneBy());
                c.setDoneAt(was.getDoneAt());
            }
            checklist.save(c);
        }
    }

    private void setLines(WorkOrder o, List<LineInput> in) {
        lines.deleteByWorkOrderId(o.getId());
        lines.flush();
        List<WoLine> ls = new ArrayList<>();
        short pos = 1;
        for (LineInput i : in) {
            WoLine l = new WoLine();
            l.setId(Ids.next());
            l.setOrgId(o.getOrgId());
            l.setWorkOrderId(o.getId());
            l.setPosition(pos++);
            l.setKind(i.kind());
            l.setDescription(i.description().strip());
            l.setQuantity(i.quantity().setScale(3, java.math.RoundingMode.HALF_UP));
            l.setUnitPrice(i.unitPrice().setScale(2, java.math.RoundingMode.HALF_UP));
            ls.add(l);
        }
        WoLine.totals(o, ls);
        lines.saveAll(ls);
        o.setUpdatedAt(clock.instant());
    }

    /** A draft approved for less than its new total needs approval again. */
    private void afterTotalsChanged(WorkOrder o) {
        if (WorkOrder.DRAFT.equals(o.getStatus()) && WorkOrder.APPROVED.equals(o.getApprovalState())
                && (o.getApprovedTotal() == null || o.getTotal().compareTo(o.getApprovedTotal()) > 0)) {
            o.setApprovalState(WorkOrder.NONE);
        }
    }

    /** No changes while the approver looks at it, unless they sent it back for changes. */
    private void requireNotWaiting(OpsAccess.Who w, WorkOrder o) {
        if (WorkOrder.PENDING.equals(o.getApprovalState()) && !"CHANGES_REQUESTED".equals(approvalStatus(w.orgId(), o))) {
            throw new BusinessException(ErrorCode.INVALID_STATE, "This work order is waiting for approval", List.of());
        }
    }

    private static boolean needsApproval(WorkOrder o, OpsSettings s) {
        BigDecimal threshold = s.getApprovalThreshold();
        if (threshold == null || o.getTotal().compareTo(threshold) <= 0) {
            return false;
        }
        return !(WorkOrder.APPROVED.equals(o.getApprovalState()) && o.getApprovedTotal() != null
                && o.getTotal().compareTo(o.getApprovedTotal()) <= 0);
    }

    private static void approved(WorkOrder o) {
        o.setApprovalState(WorkOrder.APPROVED);
        o.setApprovedTotal(o.getTotal());
    }

    private boolean noOtherAdmin(OpsAccess.Who w) {
        return memberships.findByOrgIdOrderByCreatedAt(w.orgId()).stream().noneMatch(m -> Membership.ACTIVE.equals(m.getStatus())
                && m.getRole().isAdmin() && !m.getUserId().equals(w.userId()));
    }

    private void toScheduled(WorkOrder o, String slug, UUID actorId) {
        o.setStatus(WorkOrder.SCHEDULED);
        o.setUpdatedAt(clock.instant());
        activity.record(o.getOrgId(), OpsAccess.MODULE, RECORD, o.getId(), actorId, "service.workorder.scheduled",
                Map.of("number", o.getNumber(), "start", o.getScheduledStart().toString()));
        notifyScheduled(o.getOrgId(), slug, actorId, o, views.technicians(o.getId()));
    }

    private void notifyScheduled(UUID orgId, String slug, UUID actorId, WorkOrder o, Collection<UUID> to) {
        if (to.isEmpty() || o.getScheduledStart() == null || WorkOrder.DRAFT.equals(o.getStatus())) {
            return;
        }
        LocalDate day = o.getScheduledStart().atZone(CalendarService.ZONE).toLocalDate();
        notifications.send(orgId, to, actorId, "service.workorder.assigned",
                Text.of("Work order for you: {number} on {date}", Map.of("number", o.getNumber(), "date", day.toString())),
                Text.raw(o.getTitle()), link(slug, o.getId()));
    }

    private String approvalStatus(UUID orgId, WorkOrder o) {
        return o.getApprovalId() == null ? null : approvals.statuses(orgId, List.of(o.getApprovalId())).get(o.getApprovalId());
    }

    private boolean canEditLines(OpsAccess.Who w, WorkOrder o) {
        if (w.manager()) {
            return o.isOpen();
        }
        return WorkOrder.IN_PROGRESS.equals(o.getStatus()) || WorkOrder.ON_HOLD.equals(o.getStatus());
    }

    private WorkOrderView view(OpsAccess.Who w, WorkOrder o) {
        WorkOrderSummary s = views.workOrders(w.orgId(), List.of(o)).get(0);
        OpsSettings set = settings.of(w.orgId());
        Map<UUID, Ref> sites = views.siteRefs(w.orgId(), Collections.singletonList(o.getSiteId()));
        Ticket t = o.getTicketId() == null ? null : tickets.findByIdAndOrgId(o.getTicketId(), w.orgId()).orElse(null);
        var plan = o.getPlanId() == null ? null : plans.findByIdAndOrgId(o.getPlanId(), w.orgId()).orElse(null);
        List<ChecklistItem> cs = checklist.findByWorkOrderIdOrderByPosition(o.getId());
        Map<UUID, PersonRef> ps = people.of(java.util.stream.Stream.concat(cs.stream().map(ChecklistItem::getDoneBy),
                java.util.stream.Stream.of(o.getCompletedBy(), o.getCreatedBy())).filter(Objects::nonNull).toList());
        String approval = approvalStatus(w.orgId(), o);
        boolean mine = s.technicians().stream().anyMatch(p -> p.id().equals(w.userId()));
        boolean pending = WorkOrder.PENDING.equals(o.getApprovalState()) && !"CHANGES_REQUESTED".equals(approval);
        boolean act = w.manager() || mine;
        return new WorkOrderView(s, o.getDescription(), OpsViews.ref(sites, o.getSiteId()),
                t == null ? null : new Ref(t.getId(), t.getTitle()), t == null ? null : t.getNumber(),
                plan == null ? null : new Ref(plan.getId(), plan.getTitle()), o.getPlanDue(), o.getPartsTotal(), o.getLabourTotal(),
                o.getApprovalId(), approval, o.getApprovedTotal(), set.getApprovalThreshold(), needsApproval(o, set),
                o.getHoldReason(), o.getStartedAt(), o.getCompletedAt(), o.getCompletedBy() == null ? null : ps.get(o.getCompletedBy()),
                o.getCompletionNotes(), o.getSignedBy(), o.getCancelReason(), o.getCreatedBy() == null ? null : ps.get(o.getCreatedBy()),
                cs.stream().map(c -> new CheckView(c.getId(), c.getPosition(), c.getLabel(), c.isDone(),
                        c.getDoneBy() == null ? null : ps.get(c.getDoneBy()), c.getDoneAt())).toList(),
                lines.findByWorkOrderIdOrderByPosition(o.getId()).stream().map(l -> new LineView(l.getId(), l.getPosition(), l.getKind(),
                        l.getDescription(), l.getQuantity(), l.getUnitPrice(), l.getAmount())).toList(),
                w.manager() && EDITABLE.contains(o.getStatus()) && !pending,
                w.manager() && WorkOrder.DRAFT.equals(o.getStatus()) && !WorkOrder.PENDING.equals(o.getApprovalState()),
                act && (WorkOrder.SCHEDULED.equals(o.getStatus()) || WorkOrder.ON_HOLD.equals(o.getStatus())),
                act && WorkOrder.IN_PROGRESS.equals(o.getStatus()),
                act && WorkOrder.IN_PROGRESS.equals(o.getStatus()),
                w.manager() && o.isOpen(),
                act && canEditLines(w, o) && !pending,
                act && WORKING.contains(o.getStatus()));
    }

    private static UUID uuid(String s) {
        try {
            return UUID.fromString(s);
        } catch (IllegalArgumentException e) {
            throw BusinessException.field(ErrorCode.VALIDATION_FAILED, "technician", "Choose active technicians");
        }
    }
