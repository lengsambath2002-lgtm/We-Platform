    /**
     * Soonest scheduled first (unscheduled drafts last). {@code status}: one status, or OPEN (not completed or
     * cancelled); {@code technician}: "me" or a user id; {@code from}–{@code to}: scheduled start days. Technicians
     * only get their own.
     */
    @Transactional(readOnly = true)
    public PageResponse<WorkOrderSummary> list(String slug, String q, String status, String technician, UUID ticketId,
            UUID assetId, LocalDate from, LocalDate to, int page, int size) {
        OpsAccess.Who w = access.require(slug);
        Specification<WorkOrder> spec = (o, query, cb) -> cb.equal(o.get("orgId"), w.orgId());
        UUID tech = !w.manager() || "me".equals(technician) ? w.userId()
                : technician == null || technician.isBlank() ? null : uuid(technician);
        if (tech != null) {
            spec = spec.and((o, query, cb) -> {
                var sub = query.subquery(UUID.class);
                var t = sub.from(WoTechnician.class);
                sub.select(t.get("userId")).where(cb.equal(t.get("workOrderId"), o.get("id")), cb.equal(t.get("userId"), tech));
                return cb.exists(sub);
            });
        }
        if ("OPEN".equals(status)) {
            spec = spec.and((o, query, cb) -> o.get("status").in(WorkOrder.DRAFT, WorkOrder.SCHEDULED, WorkOrder.IN_PROGRESS,
                    WorkOrder.ON_HOLD));
        } else if (status != null && !status.isBlank()) {
            spec = spec.and((o, query, cb) -> cb.equal(o.get("status"), status));
        }
        if (ticketId != null) {
            spec = spec.and((o, query, cb) -> cb.equal(o.get("ticketId"), ticketId));
        }
        if (assetId != null) {
            spec = spec.and((o, query, cb) -> cb.equal(o.get("assetId"), assetId));
        }
        if (from != null) {
            Instant f = from.atStartOfDay(CalendarService.ZONE).toInstant();
            spec = spec.and((o, query, cb) -> cb.greaterThanOrEqualTo(o.get("scheduledStart"), f));
        }
        if (to != null) {
            Instant t = to.plusDays(1).atStartOfDay(CalendarService.ZONE).toInstant();
            spec = spec.and((o, query, cb) -> cb.lessThan(o.get("scheduledStart"), t));
        }
        if (q != null && !q.isBlank()) {
            String like = OpsPeople.like(q);
            spec = spec.and((o, query, cb) -> cb.or(cb.like(cb.lower(o.get("number")), like, '\\'),
                    cb.like(cb.lower(o.get("title")), like, '\\')));
        }
        Page<WorkOrder> found = workOrders.findAll(spec, PageRequest.of(Math.max(page, 0),
                Math.min(Math.max(size, 1), OpsCustomerService.MAX_PAGE),
                Sort.by(Sort.Order.asc("scheduledStart"), Sort.Order.desc("createdAt"))));
        return PageResponse.of(new PageImpl<>(views.workOrders(w.orgId(), found.getContent()), found.getPageable(),
                found.getTotalElements()));
    }

