    @Transactional
    public WorkOrderView create(String slug, WorkOrderRequest in) {
        OpsAccess.Who w = access.requireManager(slug);
        WorkOrder draft = blank(w.orgId(), w.userId());
        WorkOrder o = draft;
        UUID customerId = in.customerId();
        UUID siteId = in.siteId();
        UUID assetId = in.assetId();
        Ticket ticket = null;
        if (in.ticketId() != null) {
            ticket = ticketService.lockForWork(w, in.ticketId());
            if (!ticket.isOpen()) {
                throw BusinessException.field(ErrorCode.VALIDATION_FAILED, "ticketId", "This ticket is resolved or closed");
            }
            // From a ticket: its customer, site and asset unless the request names others.
            if (customerId == null && siteId == null && assetId == null) {
                customerId = ticket.getCustomerId();
                siteId = ticket.getSiteId();
                assetId = ticket.getAssetId();
            }
            o.setTicketId(ticket.getId());
        }
        o.setNumber(settings.nextNumber(w.orgId(), "WORK_ORDER"));
        details(w, o, in, customerId, siteId, assetId, false);
        // Ids are assigned here, so save() merges: keep working on the managed copy it returns.
        o = workOrders.saveAndFlush(o);
        setTechnicians(w, o, in.technicianIds() == null ? List.of() : in.technicianIds());
        setChecklist(o, in.checklist() == null ? List.of() : in.checklist());
        setLines(o, in.lines() == null ? List.of() : in.lines());
        activity.record(w.orgId(), OpsAccess.MODULE, RECORD, o.getId(), w.userId(), "service.workorder.created",
                ticket == null ? Map.of("number", o.getNumber(), "title", o.getTitle())
                        : Map.of("number", o.getNumber(), "title", o.getTitle(), "ticket", ticket.getNumber()));
        if (ticket != null) {
            ticketService.workStarted(w, ticket);
            activity.record(w.orgId(), OpsAccess.MODULE, TicketService.RECORD, ticket.getId(), w.userId(),
                    "service.ticket.workorder", Map.of("number", ticket.getNumber(), "workOrder", o.getNumber()));
        }
        return view(w, o);
    }

    @Transactional
    public WorkOrderView update(String slug, UUID id, WorkOrderRequest in) {
        OpsAccess.Who w = access.requireManager(slug);
        WorkOrder o = lock(w, id);
        if (!EDITABLE.contains(o.getStatus())) {
            throw new BusinessException(ErrorCode.INVALID_STATE, "Only a draft, scheduled or on-hold work order can be changed", List.of());
        }
        requireNotWaiting(w, o);
        boolean sameCustomer = in.customerId() != null && in.customerId().equals(o.getCustomerId());
        details(w, o, in, in.customerId(), in.siteId(), in.assetId(), sameCustomer);
        List<UUID> before = views.technicians(o.getId());
        setTechnicians(w, o, in.technicianIds() == null ? List.of() : in.technicianIds());
        setChecklist(o, in.checklist() == null ? List.of() : in.checklist());
        setLines(o, in.lines() == null ? List.of() : in.lines());
        afterTotalsChanged(o);
        activity.record(w.orgId(), OpsAccess.MODULE, RECORD, o.getId(), w.userId(), "service.workorder.updated",
                Map.of("number", o.getNumber(), "total", o.getTotal().toPlainString()));
        if (WORKING.contains(o.getStatus())) {
            List<UUID> added = views.technicians(o.getId()).stream().filter(u -> !before.contains(u)).toList();
            notifyScheduled(w.orgId(), w.ctx().slug(), w.userId(), o, added);
        }
        return view(w, o);
    }

    /**
     * Schedules a draft: it needs a window and a technician. Above the threshold (and not yet approved for this
     * total) it goes to approval instead, and is scheduled when approved.
     */
    @Transactional
    public WorkOrderView schedule(String slug, UUID id) {
        OpsAccess.Who w = access.requireManager(slug);
        WorkOrder o = lock(w, id);
        if (!WorkOrder.DRAFT.equals(o.getStatus())) {
            throw new BusinessException(ErrorCode.INVALID_STATE, "Only a draft work order can be scheduled", List.of());
        }
        if (o.getScheduledStart() == null || o.getScheduledEnd() == null) {
            throw BusinessException.field(ErrorCode.VALIDATION_FAILED, "scheduledStart", "Set when the work happens first");
        }
        if (views.technicians(o.getId()).isEmpty()) {
            throw BusinessException.field(ErrorCode.VALIDATION_FAILED, "technicianIds", "Assign a technician first");
        }
        if (WorkOrder.PENDING.equals(o.getApprovalState())) {
            throw new BusinessException(ErrorCode.INVALID_STATE, "This work order is waiting for approval", List.of());
        }
        if (needsApproval(o, settings.of(w.orgId()))) {
            if (w.ctx().isAdmin() && noOtherAdmin(w)) {
                // Nobody else could decide: an organisation's only Admin approves their own (and the log says so).
                approved(o);
                activity.record(w.orgId(), OpsAccess.MODULE, RECORD, o.getId(), w.userId(), "service.workorder.self_approved",
                        Map.of("number", o.getNumber(), "total", o.getTotal().toPlainString()));
            } else {
                UUID workflow = workflows.ensure(w.ctx(), OpsAccess.MODULE, WORKFLOW, new StepInput("ORG_ROLE", null, "ADMIN"));
                o.setApprovalState(WorkOrder.PENDING);
                workOrders.saveAndFlush(o);
                ApprovalDetail d = approvals.submit(w.ctx().slug(), new SubmitRequest(workflow, OpsAccess.MODULE, RECORD, o.getId(),
                        null));
                o.setApprovalId(d.summary().id());
                o.setUpdatedAt(clock.instant());
                return view(w, o);
            }
        }
        toScheduled(o, w.ctx().slug(), w.userId());
        return view(w, o);
    }

    @Transactional
    public WorkOrderView cancel(String slug, UUID id, String reason) {
        OpsAccess.Who w = access.requireManager(slug);
        WorkOrder o = lock(w, id);
        if (!o.isOpen()) {
            throw new BusinessException(ErrorCode.INVALID_STATE, "This work order is already completed or cancelled", List.of());
        }
        if (WorkOrder.PENDING.equals(o.getApprovalState())) {
            // The request would be about nothing any more.
            approvalCleanup.recordsDeleted(w.orgId(), OpsAccess.MODULE, RECORD, List.of(o.getId()));
            o.setApprovalState(WorkOrder.NONE);
            o.setApprovalId(null);
        }
        o.setStatus(WorkOrder.CANCELLED);
        o.setCancelReason(reason.strip());
        o.setUpdatedAt(clock.instant());
        activity.record(w.orgId(), OpsAccess.MODULE, RECORD, o.getId(), w.userId(), "service.workorder.cancelled",
                Map.of("number", o.getNumber(), "reason", o.getCancelReason()));
        return view(w, o);
    }

